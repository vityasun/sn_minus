-- Оригинал запоминается один раз (на случай перезагрузки файла)
MODULE.OriginalGetPhrase = MODULE.OriginalGetPhrase or language.GetPhrase
local original_GetPhrase = MODULE.OriginalGetPhrase

function language.GetPhrase(key)
    if MODULE:IsEnabled() and overrides[key] then
        return overrides[key]
    end
    return original_GetPhrase(key)
end
